const CategoryPage = () => {
  const { categoryId } = useParams();
  const navigate = useNavigate();
  const [searchValue, setSearchValue] = useState("");
  const screens = useBreakpoint();
  const isMobile = !screens.md;
  const { token } = theme.useToken();

  const {
    data,
    isLoading,
    isError,
    error,
    refetch,
  } = useQuery<CategoryQueryResponse, Error>({
    queryKey: ["category", categoryId],
    queryFn: () => fetchCategory(categoryId),
    enabled: Boolean(categoryId),
    staleTime: 60 * 1000,
  });

  const labelMap = useMemo(() => buildLabelMap(data?.info?.disciplines_verbose), [data?.info?.disciplines_verbose]);

  const processedResults = useMemo(() => {
    return (data?.results ?? []).map((row, index) => ({
      ...row,
      key: row.id,
      displayRank: row.final_position ?? index + 1,
    }));
  }, [data?.results]);

  const filteredResults = useMemo(() => {
    const term = searchValue.trim().toLowerCase();
    if (!term) return processedResults;
    return processedResults.filter((row) => {
      const fullName = row.player?.full_name?.toLowerCase() ?? "";
      const clubName = row.player?.club?.name?.toLowerCase() ?? "";
      const surnameFirst = getSurnameFirstValue(row.player).toLowerCase();
      return fullName.includes(term) || surnameFirst.includes(term) || clubName.includes(term);
    });
  }, [processedResults, searchValue]);

  const overallColumns = useOverallColumns(data?.info, labelMap);

  const disciplineTables = useMemo(() => {
    const entries = (data?.info?.disciplines ?? []).map((code) => {
      const label = labelMap.get(code) ?? code;

      const sortedRows = [...filteredResults]
        .sort((left, right) => {
          const leftPlacement = getDisciplinePlacement(left, code)?.position;
          const rightPlacement = getDisciplinePlacement(right, code)?.position;

          if (leftPlacement && rightPlacement && leftPlacement !== rightPlacement) {
            return leftPlacement - rightPlacement;
          }

          if (leftPlacement && !rightPlacement) {
            return -1;
          }

          if (!leftPlacement && rightPlacement) {
            return 1;
          }

          const leftPoints = left.discipline_points?.[code] ?? Number.NEGATIVE_INFINITY;
          const rightPoints = right.discipline_points?.[code] ?? Number.NEGATIVE_INFINITY;

          if (leftPoints !== rightPoints) {
            return rightPoints - leftPoints;
          }

          return comparePlayersBySurname(left.player, right.player);
        })
        .map((row, index) => ({
          ...row,
          disciplineRank: getDisciplinePlacement(row, code)?.position ?? index + 1,
        }));

      return {
        code,
        label,
        columns: createDisciplineColumns(code),
        rows: sortedRows,
      };
    });

    return entries;
  }, [data?.info?.disciplines, filteredResults, labelMap]);

  const expandedRowRender = useCallback(
    (record: ProcessedCategoryRow) => {
      const disciplineBlocks = (data?.info?.disciplines ?? []).map((code) => {
        const label = labelMap.get(code) ?? code;
        switch (code) {
          case "snatch":
            return renderSnatchDetails(code, label, record.snatch_result, token);
          case "tgu":
            return renderAttemptsDetails(code, label, record.tgu_result, token);
          case "squat":
            return renderAttemptsDetails(code, label, record.squat_result, token);
          case "see_saw_press":
            return renderAttemptsDetails(code, label, record.see_saw_press_result, token);
          case "pistol":
            return renderAttemptsDetails(code, label, record.pistol_result, token);
          case "pull_up":
            return renderAttemptsDetails(code, label, record.pull_up_result, token);
          default:
            return (
              <Space key={code} direction="vertical" size={8} style={detailContainerStyle(token)}>
                <Text strong style={detailHeaderStyle}>
                  {label}
                </Text>
                <Text type="secondary">Brak danych dla tej konkurencji.</Text>
              </Space>
            );
        }
      });

      if (!disciplineBlocks.length) {
        return null;
      }

      return (
        <Space
          direction="vertical"
          size={12}
          style={{
            width: "100%",
            padding: 16,
            borderRadius: token.borderRadiusLG,
            background: token.colorWarning,
            border: `1px solid ${token.colorBorder}`,
          }}
        >
          {disciplineBlocks}
        </Space>
      );
    },
    [data?.info?.disciplines, labelMap, token],
  );

  if (isLoading) {
    return (
      <Flex align="center" justify="center" style={{ minHeight: 320 }}>
        <Spin size="large" tip="Ładujemy wyniki kategorii..." />
      </Flex>
    );
  }

  if (isError) {
    return (
      <Flex align="center" justify="center" style={{ minHeight: 320 }}>
        <Alert
          type="error"
          showIcon
          message="Nie udało się wczytać danych kategorii"
          description={error?.message ?? "Spróbuj ponownie."}
          action={
            <Button onClick={() => refetch()} icon={<ReloadOutlined />}>
              Spróbuj ponownie
            </Button>
          }
        />
      </Flex>
    );
  }

  if (!data?.info) {
    return (
      <Flex align="center" justify="center" style={{ minHeight: 240 }}>
        <Alert type="warning" message="Brak danych kategorii" />
      </Flex>
    );
  }

  const { info } = data;
  const cardBackground = token.colorBgContainer;
  const cardBorder = `1px solid ${token.colorBorder}`;
  const pageGap = isMobile ? 16 : 24;
  const toolbarStickyTop = isMobile
    ? layoutConstants.headerHeight + 12
    : undefined;
  const tableStickyOffset = layoutConstants.headerHeight + (isMobile ? 12 : 24);

  return (
    <Space direction="vertical" size={pageGap} style={{ width: "100%" }}>
      <Card
        size="small"
        style={{
          background: cardBackground,
          border: cardBorder,
          position: isMobile ? "sticky" : "static",
          top: toolbarStickyTop,
          zIndex: isMobile ? (token.zIndexPopupBase ?? 1000) - 200 : undefined,
        }}
        bodyStyle={{
          padding: isMobile ? 12 : 16,
        }}
      >
        <Flex
          align={isMobile ? "stretch" : "center"}
          justify="space-between"
          gap={isMobile ? 12 : 20}
          vertical={isMobile}
        >
          <Button
            icon={<ArrowLeftOutlined />}
            onClick={() => navigate(-1)}
            block={isMobile}
          >
            Wróć
          </Button>
          <Flex
            gap={12}
            wrap
            justify={isMobile ? "flex-start" : "flex-end"}
            style={{ width: isMobile ? "100%" : "auto" }}
          >
            <Search
              allowClear
              placeholder="Filtruj zawodników lub klub"
              value={searchValue}
              onChange={(event) => setSearchValue(event.target.value)}
              style={{ flex: isMobile ? "1 1 100%" : "0 0 320px" }}
            />
            <Button icon={<ReloadOutlined />} onClick={() => refetch()} block={isMobile}>
              Odśwież
            </Button>
          </Flex>
        </Flex>
      </Card>

      <Card
        size="small"
        style={{
          background: cardBackground,
          border: cardBorder,
        }}
        bodyStyle={{
          display: "grid",
          gap: isMobile ? 12 : 16,
        }}
      >
        <Title level={2} style={{ margin: 0 }}>
          {info.name}
        </Title>
        {info.drop_worst_result && (
          <Paragraph>
            W klasyfikacji pomijamy najgorszy wynik zawodnika (Snatch zawsze liczony).
          </Paragraph>
        )}
        <Space wrap size={[8, 8]}>
          {(info.disciplines_verbose ?? []).map((disc) => (
            <Tag
              key={disc.code}
              bordered={false}
              style={{
                background: token.colorBgElevated,
                color: token.colorLink,
                letterSpacing: "0.05em",
              }}
            >
              {disc.label}
            </Tag>
          ))}
        </Space>
      </Card>

      <Space direction="vertical" size={pageGap} style={{ width: "100%" }}>
        {SHOW_GENERAL_CLASSIFICATION && (
          <Card
            size="small"
            style={{
              background: cardBackground,
              border: cardBorder,
            }}
            headStyle={{
              borderBottom: "none",
              paddingBottom: 0,
            }}
            bodyStyle={{
              padding: isMobile ? 12 : 16,
            }}
            title={<Title level={3} style={{ margin: 0 }}>Klasyfikacja generalna</Title>}
          >
            <Table<ProcessedCategoryRow>
              columns={overallColumns}
              dataSource={filteredResults}
              rowKey={(record) => record.id}
              pagination={
                isMobile
                  ? { pageSize: 15, showSizeChanger: false }
                  : { pageSize: 25, showSizeChanger: true }
              }
              expandable={{
                expandRowByClick: true,
                expandedRowRender,
              }}
              size={isMobile ? "small" : "middle"}
              scroll={{ x: "max-content" }}
              sticky={{ offsetHeader: tableStickyOffset }}
            />
          </Card>
        )}

        {disciplineTables.map((table) => (
          <Card
            key={table.code}
            size="small"
            style={{
              background: cardBackground,
              border: cardBorder,
            }}
            headStyle={{
              borderBottom: "none",
              paddingBottom: 0,
            }}
            bodyStyle={{
              padding: isMobile ? 12 : 16,
            }}
            title={<Title level={3} style={{ margin: 0 }}>Wyniki · {table.label}</Title>}
          >
            <Table<DisciplineRow>
              columns={table.columns}
              dataSource={table.rows}
              rowKey={(record) => `${table.code}-${record.id}`}
              pagination={
                isMobile
                  ? { pageSize: 15, showSizeChanger: false }
                  : { pageSize: 25, showSizeChanger: true }
              }
              size={isMobile ? "small" : "middle"}
              scroll={{ x: "max-content" }}
              sticky={{ offsetHeader: tableStickyOffset }}
            />
          </Card>
        ))}
      </Space>
    </Space>
  );
};

